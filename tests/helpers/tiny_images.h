/* One row per vector: what detect.c must sniff it as, the gdk-pixbuf
 * module name that decodes it (so a test can skip a format whose module is
 * not installed instead of failing on CI), and whether it needs the jxl
 * feature (gdk-pixbuf never gets to try a JXL; see loader.c). */
typedef struct {
   const char   *c_name;
   const guint8 *p_bytes;
   gsize         u_len;
   GgazeFormat   e_format;
   const char   *c_pixbuf_module;
   gboolean      b_needs_jxl;
} TinyImage;

