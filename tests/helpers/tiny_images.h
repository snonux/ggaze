/*:*
 * ggaze — the smallest real 1x1 image per format, as inline byte vectors
 *
 * Shared by tests/test_detect.c (the per-signature minimum-file-length gate
 * must ACCEPT every one of these: they are real, complete, decodable files,
 * so they prove the gate does not over-tighten) and
 * tests/test_loader_pixbuf.c (each must LOAD as 1x1 through loader_load()
 * wherever this build has a decoder for it, and a JXL must be refused with
 * G_IO_ERROR_NOT_SUPPORTED when the jxl feature is off). Task tb2.
 *
 * Provenance (regenerate with the same tools if a vector ever needs to
 * change; sizes are what the tools emitted, not tuned by hand):
 *   ImageMagick 7.1.2 / libwebp 1.6 / libjxl 0.11:
 *     magick -size 1x1 xc:red -define webp:lossless=true  (lossless WebP)
 *     magick -size 1x1 xc:red -strip                      (GIF, ICO, JXL)
 *     magick -size 1x1 xc:gray -type Grayscale -strip -quality 1 (JPEG)
 *   Pillow 12.3:
 *     Image.new("RGB",(1,1)).save(..., quality=0, method=0) (lossy WebP)
 *   Hand-built with the Python stdlib (struct + zlib):
 *     PNG: signature + IHDR (1x1, 8-bit gray) + one-byte IDAT + IEND
 *     TIFF: header + the nine mandatory baseline tags + one 8-bit sample,
 *           once "II" and once "MM"
 *     JXL container: "JXL " signature box + ftyp(jxl ) + a jxlc box holding
 *           the ImageMagick codestream above
 * Every vector was verified to decode as 1x1 through gdk-pixbuf (glycin
 * loaders, Fedora 44) and `magick identify` before being embedded.
 *
 * Copyright (c) 2026 ggaze contributors
 * SPDX-License-Identifier: GPL-3.0-or-later
 *:*/

